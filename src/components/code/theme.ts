function highlightStyle(): HighlightStyle {
  return HighlightStyle.define([
    { tag: [t.keyword, t.controlKeyword, t.moduleKeyword, t.definitionKeyword, t.operatorKeyword, t.modifier, t.self], color: "var(--cb-syn-keyword)" },
    { tag: [t.typeName, t.className, t.namespace, t.definition(t.typeName), t.definition(t.className)], color: "var(--cb-syn-type)" },
    { tag: [t.function(t.variableName), t.function(t.propertyName), t.function(t.definition(t.variableName))], color: "var(--cb-syn-function)" },
    { tag: [t.propertyName, t.definition(t.propertyName)], color: "var(--cb-syn-property)" },
    { tag: [t.number, t.bool, t.null, t.atom], color: "var(--cb-syn-number)" },
    { tag: [t.string, t.special(t.string), t.regexp, t.escape], color: "var(--cb-syn-string)" },
    // Upright: the engine sources are teaching material with long comments.
    { tag: [t.lineComment, t.blockComment, t.comment, t.docComment], color: "var(--cb-syn-comment)" },
    { tag: [t.meta, t.annotation], color: "var(--cb-syn-meta)" },
    {
      tag: [t.operator, t.arithmeticOperator, t.logicOperator, t.bitwiseOperator, t.compareOperator, t.updateOperator, t.definitionOperator, t.derefOperator],
      color: "var(--cb-syn-operator)",
    },
    { tag: [t.punctuation, t.separator, t.bracket, t.paren, t.brace, t.squareBracket, t.angleBracket], color: "var(--cb-syn-punctuation)" },
    { tag: [t.variableName, t.definition(t.variableName), t.labelName], color: "var(--cb-syn-variable)" },
    { tag: t.heading, fontWeight: "700" },
    { tag: t.emphasis, fontStyle: "italic" },
    { tag: t.strong, fontWeight: "700" },
    { tag: t.link, textDecoration: "underline" },
    { tag: t.invalid, color: "var(--danger)" },
  ]);
}

let cached: Extension | null = null;

/** The editor theme + syntax highlighting (shared by all editors). */
export function editorTheme(): Extension {
  cached ??= [EditorView.theme(themeSpec()), syntaxHighlighting(highlightStyle())];
  return cached;
}
