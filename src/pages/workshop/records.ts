// Pure builders for the Workshop: save patches for each kind of edit, and the new engine
// records created by Duplicate / Convert. No React, no storage — the page passes ids and clocks
// in, so everything here is unit-testable.
import type { EngineKind, EngineRecord } from "@/types";

/** What the builders need from the outside world. */
export interface RecordDeps {
  newId(): string;
  now(): number;
}

// ---------------------------------------------------------------------------------------------
// Save patches (always complete values for the fields they touch: enginesRepo.update merges
// shallowly, so `files` must be the whole map).

/** A blocks edit: the workspace and the eval.ts generated from it, stamped with the generator version. */
export function blocksPatch(engine: EngineRecord, workspace: object, code: string, generatorVersion: number): Partial<EngineRecord> {
  return { blocks: workspace, files: { ...(engine.files ?? {}), "eval.ts": code }, generatorVersion };
}

/** One file's new contents. */
export function filePatch(engine: EngineRecord, path: string, text: string): Partial<EngineRecord> {
  return { files: { ...(engine.files ?? {}), [path]: text } };
}

/** The engine's own source files as stored (eval/nnue: overrides; full/scratch: the whole tree). */
export function ownFiles(engine: EngineRecord): Record<string, string> {
  return engine.files ?? {};
}

/** Entry file used for compiling (the record's, defaulting to main.ts). */
export function entryOf(engine: EngineRecord): string {
  return engine.entry || "main.ts";
}

/** Tags without the built-in "starter" marker (copies are the user's own engines). */
function ownTags(tags: readonly string[] | undefined): string[] {
  return (tags ?? []).filter((t) => t !== "starter");
}

/**
 * `base`, or `base (2)`, `base (3)` … — the first one no existing engine uses (case-insensitive).
 */
export function uniqueName(base: string, existing: readonly string[]): string {
  const taken = new Set(existing.map((n) => n.trim().toLowerCase()));
  if (!taken.has(base.trim().toLowerCase())) return base;
  for (let i = 2; i < 1000; i++) {
    const candidate = `${base} (${i})`;
    if (!taken.has(candidate.toLowerCase())) return candidate;
  }
  return `${base} (${Date.now()})`;
}

/** Fields every derived engine gets fresh. */
function derived(src: EngineRecord, deps: RecordDeps, name: string): Pick<EngineRecord, "id" | "name" | "createdAt" | "updatedAt" | "parentId" | "builtin" | "tags"> {
  const now = deps.now();
  return { id: deps.newId(), name, createdAt: now, updatedAt: now, parentId: src.id, builtin: false, tags: ownTags(src.tags) };
}

/**
 * An independent copy of an engine (same kind, sources, network and build — the build stays valid
 * because the sources are identical).
 */
export function duplicateRecord(src: EngineRecord, deps: RecordDeps, existingNames: readonly string[] = []): EngineRecord {
  const copy: EngineRecord = {
    ...src,
    ...derived(src, deps, uniqueName(`${src.name} (copy)`, existingNames)),
    options: { ...src.options },
  };
  if (src.files) copy.files = { ...src.files };
  if (src.blocks !== undefined) copy.blocks = structuredClone(src.blocks);
  return copy;
}

/** Which conversion the Convert menu offers for a kind (null = none). */
export function conversionFor(kind: EngineKind): "to-code" | "unlock-full" | null {
  if (kind === "blocks") return "to-code";
  if (kind === "eval" || kind === "nnue") return "unlock-full";
  return null;
}

const GENERATED_HEADER = "// eval.ts — generated by Chess Builder from your blocks.";
const GENERATED_HEADER_2 = "// rewritten every time the blocks change.";

/**
 * The generated eval.ts says "don't edit this file by hand"; once converted to a code engine
 * that is no longer true, so the generator's header lines are replaced. Other code is unchanged.
 */
export function convertedEvalSource(code: string, sourceName: string): string {
  const lines = code.split("\n");
  if (!lines[0]?.startsWith(GENERATED_HEADER)) return code;
  const drop = lines[1]?.startsWith(GENERATED_HEADER_2) ? 2 : 1;
  const header = [`// eval.ts — converted from the blocks of “${sourceName}”. This is ordinary AssemblyScript now:`, "// edit anything you like (the blocks engine it came from is unchanged)."];
  return [...header, ...lines.slice(drop)].join("\n");
}

/**
 * Blocks → "Convert to code": a NEW eval engine whose eval.ts is the code generated from the
 * blocks (see convertedEvalSource). The rest of the engine is the stock template, as before.
 */
export function blocksToCodeRecord(
  src: EngineRecord,
  generatedCode: string,
  deps: RecordDeps,
  templateVersion: number,
  existingNames: readonly string[] = [],
): EngineRecord {
  return {
    ...derived(src, deps, uniqueName(`${src.name} (code)`, existingNames)),
    kind: "eval",
    description: src.description,
    color: src.color,
    files: { "eval.ts": generatedCode },
    entry: "main.ts",
    templateVersion,
    networkId: src.networkId ?? null,
    options: { ...src.options },
    build: src.build ?? null,
  };
}

/**
 * eval / nnue → "Unlock the full engine source": a NEW full engine holding every template file
 * plus this engine's own overrides (normally eval.ts). The network stays attached.
 */
export function unlockFullRecord(
  src: EngineRecord,
  templateFiles: Readonly<Record<string, string>>,
  deps: RecordDeps,
  templateVersion: number,
  existingNames: readonly string[] = [],
): EngineRecord {
  return {
    ...derived(src, deps, uniqueName(`${src.name} (full)`, existingNames)),
    kind: "full",
    description: src.description,
    color: src.color,
    files: { ...templateFiles, ...(src.files ?? {}) },
    entry: entryOf(src),
    templateVersion,
    networkId: src.networkId ?? null,
    options: { ...src.options },
    build: src.build ?? null,
  };
}

/** Parses a comma-separated tag list: trimmed, non-empty, unique (case-insensitive), at most 12. */
export function parseTags(text: string): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const raw of text.split(",")) {
    const t = raw.trim().replace(/\s+/g, " ").slice(0, 32);
    if (!t || seen.has(t.toLowerCase())) continue;
    seen.add(t.toLowerCase());
    out.push(t);
    if (out.length >= 12) break;
  }
  return out;
}
